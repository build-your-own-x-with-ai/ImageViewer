/// 读取「码长表的码长」时的符号顺序。RFC 1951 §3.2.7。
///
/// ## 这张表是 deflate 里最绕的一处
///
/// 动态 Huffman 块里，码表本身也是 Huffman 编码的。要解开数据的码表，
/// 先得解开「码表的码表」—— 即 19 个码长符号（0..15 表示码长，16/17/18
/// 表示重复）各自的码长。
///
/// 这 19 个值不按 0..18 顺序存，而按下面这个乱序存。原因是实践中
/// 码长 7、8、9 附近最常用，而 16/17/18（重复指令）几乎总会出现 ——
/// 把高频的排在前面，末尾那些用不到的（比如码长 15）就可以整段省略掉，
/// 于是 HCLEN 字段只需声明「前 N 个」。
///
/// 换句话说：这个顺序不是为了解码方便，而是为了**省几个字节**。
const List<int> kCodeLengthOrder = <int>[
  16, 17, 18, 0, 8, 7, 9, 6, 10, 5, 11, 4, 12, 3, 13, 2, 14, 1, 15,
];

/// 固定 Huffman 块的字面/长度码长表。RFC 1951 §3.2.6。
///
/// 固定块的码表写死在规范里，双方都知道，所以码流里不用传 —— 这对小数据
/// 很有利（动态块光传码表就要几十字节）。
///
/// ```
/// 符号 0..143   → 8 位
/// 符号 144..255 → 9 位
/// 符号 256..279 → 7 位   ← 结束符 256 在这段，只占 7 位
/// 符号 280..287 → 8 位
/// ```
///
/// 286/287 实际不合法（长度码只到 285），但规范仍给它们分配了码长，
/// 目的是让码表保持「完整」（各码长的码字用满，无空洞）。
List<int> buildFixedLiteralLengths() {
  final List<int> lengths = List<int>.filled(288, 0);
  for (int i = 0; i < 144; i++) {
    lengths[i] = 8;
  }
  for (int i = 144; i < 256; i++) {
    lengths[i] = 9;
  }
  for (int i = 256; i < 280; i++) {
    lengths[i] = 7;
  }
  for (int i = 280; i < 288; i++) {
    lengths[i] = 8;
  }
  return lengths;
}

/// 固定 Huffman 块的距离码长表：30 个码字全是 5 位。RFC 1951 §3.2.6。
///
/// 规范给的是 32 项（含两个不合法的 30/31），同样是为了码表完整。
List<int> buildFixedDistanceLengths() => List<int>.filled(32, 5);
